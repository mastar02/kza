"""Regenerate the committed ``nexa_ml.pb`` gRPC stubs from ``crates/nexa-proto``.

Run from any cwd with an interpreter that has the pinned ``grpcio-tools``::

    uv run --no-project --python 3.13 --with grpcio-tools==1.81.0 \
        python workers/nexa-ml/scripts/gen_pb.py

CI re-runs this script and fails on ``git diff --exit-code`` (stub drift check).
Generated imports ``from nexa.v1 import X`` are rewritten deterministically to
``from nexa_ml.pb import X`` so the stubs resolve inside the ``nexa_ml`` package.
"""

import pathlib
import re
import shutil
import sys
import tempfile

from grpc_tools import protoc

WORKER_ROOT = pathlib.Path(__file__).resolve().parents[1]
REPO_ROOT = WORKER_ROOT.parents[1]
PROTO_ROOT = REPO_ROOT / "crates" / "nexa-proto" / "proto"
PROTOS = ("nexa/v1/common.proto", "nexa/v1/ml.proto")
OUT_DIR = WORKER_ROOT / "src" / "nexa_ml" / "pb"
HEADER = "# Generated by workers/nexa-ml/scripts/gen_pb.py from crates/nexa-proto. DO NOT EDIT.\n"
_IMPORT_RE = re.compile(r"^from nexa\.v1 import ", re.MULTILINE)


def main() -> int:
    """Generate stubs into a temp dir, rewrite imports and replace ``pb/`` contents."""
    with tempfile.TemporaryDirectory() as tmp:
        grpc_include = pathlib.Path(protoc.__file__).parent / "_proto"
        rc = protoc.main(
            [
                "grpc_tools.protoc",
                f"-I{PROTO_ROOT}",
                f"-I{grpc_include}",
                f"--python_out={tmp}",
                f"--pyi_out={tmp}",
                f"--grpc_python_out={tmp}",
                *PROTOS,
            ]
        )
        if rc != 0:
            return rc
        generated = sorted((pathlib.Path(tmp) / "nexa" / "v1").glob("*.py*"))
        if not generated:
            return 1
        for stale in OUT_DIR.glob("*_pb2*.py*"):
            stale.unlink()
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for src in generated:
            text = _IMPORT_RE.sub("from nexa_ml.pb import ", src.read_text())
            (OUT_DIR / src.name).write_text(HEADER + text)
        init = OUT_DIR / "__init__.py"
        init.write_text('"""Generated protobuf/gRPC stubs for ``nexa.v1`` (see scripts/gen_pb.py)."""\n')
    shutil.rmtree(OUT_DIR / "__pycache__", ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
