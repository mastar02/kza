"""Whisper Rioplatense LoRA fine-tuning + CTranslate2 export pipeline (1x RTX 3070 8 GB).

Consumes ``<curated_dir>/stt/metadata.jsonl`` generated by ``TrainingDatasetHub``.
By default excludes clips still flagged ``needs_review=True`` so unverified
Whisper-vs-Parakeet disagreements never poison the fine-tuned weights.

Supports both production targets:
  - ``openai/whisper-large-v3`` (ambient multi-mic pool on ``cuda:0``)
  - ``openai/whisper-large-v3-turbo`` (fast-path on ``cuda:1``, 0 MB extra VRAM
    once merged and converted to CTranslate2 ``int8_float16``).
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
import json
import os
from pathlib import Path
import subprocess
import sys

from src.audio.clip_io import write_private_bytes
from src.core.paths import TRAINING_OUTPUT_WHISPER


@dataclass(frozen=True)
class WhisperLoraConfig:
    """Configuration for Rioplatense Whisper LoRA fine-tuning on 8 GB VRAM."""

    curated_dir: Path
    output_dir: Path = Path(TRAINING_OUTPUT_WHISPER)
    base_model: str = "openai/whisper-large-v3-turbo"
    language: str = "es"
    gpu_index: int = 0
    epochs: int = 3
    batch_size: int = 2
    gradient_accumulation_steps: int = 8
    learning_rate: float = 1e-4
    lora_r: int = 16
    lora_alpha: int = 32
    lora_dropout: float = 0.05
    min_samples: int = 20
    val_ratio: float = 0.1
    include_unreviewed: bool = False
    ct2_quantization: str = "int8_float16"


@dataclass(frozen=True)
class WhisperLoraPlan:
    """Prepared training split, script path, and CTranslate2 export target."""

    base_model: str
    gpu_index: int
    total_samples: int
    train_samples: int
    val_samples: int
    skipped_needs_review: int
    skipped_missing_audio: int
    train_manifest: str
    val_manifest: str
    script_path: str
    ct2_output_dir: str


class WhisperLoraPipeline:
    """Prepares and runs Whisper LoRA fine-tuning + CTranslate2 export."""

    def __init__(self, config: WhisperLoraConfig):
        self.config = config

    def load_verified_samples(self) -> tuple[list[dict], int, int]:
        """Load curated STT rows, filtering out unreviewed disagreements and missing WAVs."""
        meta = self.config.curated_dir / "stt" / "metadata.jsonl"
        if not meta.is_file():
            raise FileNotFoundError(f"missing_curated_stt_metadata:{meta}")

        samples: list[dict] = []
        skipped_review = 0
        skipped_audio = 0
        for line in meta.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            if not self.config.include_unreviewed and rec.get("needs_review") is True:
                skipped_review += 1
                continue
            text = str(rec.get("text") or "").strip()
            rel = rec.get("audio_path")
            if not text or not rel:
                skipped_audio += 1
                continue
            audio_path = Path(rel)
            if not audio_path.is_absolute():
                audio_path = self.config.curated_dir / audio_path
            if not audio_path.is_file():
                skipped_audio += 1
                continue
            samples.append(
                {
                    "utterance_id": rec.get("utterance_id"),
                    "audio_path": str(audio_path.resolve()),
                    "text": text,
                    "duration_s": rec.get("duration_s"),
                }
            )
        return samples, skipped_review, skipped_audio

    def prepare(self) -> WhisperLoraPlan:
        """Validate sample count, split train/val, and write the private training script."""
        samples, skipped_review, skipped_audio = self.load_verified_samples()
        if len(samples) < self.config.min_samples:
            raise ValueError(
                f"insufficient_stt_samples:{len(samples)}<{self.config.min_samples}"
            )

        out = self.config.output_dir
        out.mkdir(parents=True, exist_ok=True, mode=0o700)
        os.chmod(out, 0o700)

        val_n = max(1, int(round(len(samples) * self.config.val_ratio))) if len(samples) > 1 else 0
        train_items = samples[:-val_n] if val_n else samples
        val_items = samples[-val_n:] if val_n else samples[:1]

        train_path = out / "train.jsonl"
        val_path = out / "val.jsonl"
        write_private_bytes(
            train_path,
            ("\n".join(json.dumps(r, ensure_ascii=False) for r in train_items) + "\n").encode("utf-8"),
        )
        write_private_bytes(
            val_path,
            ("\n".join(json.dumps(r, ensure_ascii=False) for r in val_items) + "\n").encode("utf-8"),
        )

        adapter_dir = out / "lora_adapter"
        merged_dir = out / "merged_hf"
        ct2_dir = out / f"ct2_{self.config.ct2_quantization}"
        script_path = out / "run_whisper_lora.py"
        script_body = self._render_script(train_path, val_path, adapter_dir, merged_dir, ct2_dir)
        write_private_bytes(script_path, script_body.encode("utf-8"))

        plan = WhisperLoraPlan(
            base_model=self.config.base_model,
            gpu_index=self.config.gpu_index,
            total_samples=len(samples),
            train_samples=len(train_items),
            val_samples=len(val_items),
            skipped_needs_review=skipped_review,
            skipped_missing_audio=skipped_audio,
            train_manifest=str(train_path),
            val_manifest=str(val_path),
            script_path=str(script_path),
            ct2_output_dir=str(ct2_dir),
        )
        write_private_bytes(
            out / "plan.json",
            json.dumps(asdict(plan), ensure_ascii=False, indent=2).encode("utf-8"),
        )
        return plan

    def _render_script(
        self,
        train_path: Path,
        val_path: Path,
        adapter_dir: Path,
        merged_dir: Path,
        ct2_dir: Path,
    ) -> str:
        c = self.config
        return f'''#!/usr/bin/env python3
"""Auto-generated Rioplatense Whisper LoRA trainer (8 GB RTX 3070)."""
import json
import subprocess
from pathlib import Path
import soundfile as sf
import torch
from datasets import Dataset
from peft import LoraConfig, get_peft_model
from transformers import (
    Seq2SeqTrainer,
    Seq2SeqTrainingArguments,
    WhisperForConditionalGeneration,
    WhisperProcessor,
)

BASE_MODEL = {c.base_model!r}
TRAIN_PATH = Path({str(train_path)!r})
VAL_PATH = Path({str(val_path)!r})
ADAPTER_DIR = Path({str(adapter_dir)!r})
MERGED_DIR = Path({str(merged_dir)!r})
CT2_DIR = Path({str(ct2_dir)!r})

def load_rows(path: Path):
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]

def main():
    processor = WhisperProcessor.from_pretrained(BASE_MODEL, language={c.language!r}, task="transcribe")
    model = WhisperForConditionalGeneration.from_pretrained(BASE_MODEL, torch_dtype=torch.float16)
    model.config.forced_decoder_ids = processor.get_decoder_prompt_ids(language={c.language!r}, task="transcribe")
    model.config.use_cache = False
    model.gradient_checkpointing_enable()

    lora = LoraConfig(
        r={c.lora_r},
        lora_alpha={c.lora_alpha},
        lora_dropout={c.lora_dropout},
        target_modules=["q_proj", "v_proj"],
    )
    model = get_peft_model(model, lora)

    def prepare(batch):
        wav, sr = sf.read(batch["audio_path"], dtype="float32")
        feats = processor.feature_extractor(wav, sampling_rate=sr).input_features[0]
        labels = processor.tokenizer(batch["text"]).input_ids
        return {{"input_features": feats, "labels": labels}}

    train_ds = Dataset.from_list(load_rows(TRAIN_PATH)).map(prepare)
    val_ds = Dataset.from_list(load_rows(VAL_PATH)).map(prepare)

    def collate(features):
        inputs = [{{"input_features": f["input_features"]}} for f in features]
        batch = processor.feature_extractor.pad(inputs, return_tensors="pt")
        label_feats = [{{"input_ids": f["labels"]}} for f in features]
        labels_batch = processor.tokenizer.pad(label_feats, return_tensors="pt")
        labels = labels_batch["input_ids"].masked_fill(labels_batch.attention_mask.ne(1), -100)
        batch["labels"] = labels
        return batch

    args = Seq2SeqTrainingArguments(
        output_dir=str(ADAPTER_DIR),
        per_device_train_batch_size={c.batch_size},
        gradient_accumulation_steps={c.gradient_accumulation_steps},
        learning_rate={c.learning_rate},
        num_train_epochs={c.epochs},
        fp16=True,
        eval_strategy="epoch",
        save_strategy="epoch",
        logging_steps=10,
        remove_unused_columns=False,
        report_to="none",
    )
    trainer = Seq2SeqTrainer(
        model=model,
        args=args,
        train_dataset=train_ds,
        eval_dataset=val_ds,
        data_collator=collate,
    )
    trainer.train()
    model.save_pretrained(str(ADAPTER_DIR))

    merged = model.merge_and_unload()
    merged.save_pretrained(str(MERGED_DIR))
    processor.save_pretrained(str(MERGED_DIR))

    subprocess.run(
        [
            "ct2-transformers-converter",
            "--model", str(MERGED_DIR),
            "--output_dir", str(CT2_DIR),
            "--quantization", {c.ct2_quantization!r},
            "--copy_files", "tokenizer.json", "preprocessor_config.json",
            "--force",
        ],
        check=True,
    )

if __name__ == "__main__":
    main()
'''

    def run(self, *, dry_run: bool = False) -> WhisperLoraPlan:
        """Prepare the plan and optionally execute the training subprocess on ``gpu_index``."""
        plan = self.prepare()
        if dry_run:
            return plan
        env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(self.config.gpu_index))
        subprocess.run([sys.executable, plan.script_path], env=env, check=True)
        return plan
